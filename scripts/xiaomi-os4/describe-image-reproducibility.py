#!/usr/bin/env python3
import argparse
import hashlib
from pathlib import Path

SUBJECT = b"Build time autogenerated kernel key"
BUILD_ID_NOTE_PREFIX = (
    (4).to_bytes(4, "little")
    + (20).to_bytes(4, "little")
    + (3).to_bytes(4, "little")
    + b"GNU\0"
)

def all_offsets(data: bytes, needle: bytes):
    pos = 0
    while True:
        hit = data.find(needle, pos)
        if hit < 0:
            return
        yield hit
        pos = hit + 1

def locate_top_level_build_id(data: bytes) -> int:
    # A pandora R62 Image contains a few embedded GNU build-id notes. The
    # kernel's own top-level note is the last one in the final Image; this is
    # also the note normalized by the already-validated LKG model.
    starts = list(all_offsets(data, BUILD_ID_NOTE_PREFIX))
    if not starts:
        raise SystemExit("GNU build-id note not found")
    payload = max(starts) + len(BUILD_ID_NOTE_PREFIX)
    if payload + 20 > len(data):
        raise SystemExit("GNU build-id payload out of range")
    return payload

def locate_autogenerated_cert(data: bytes):
    subjects = list(all_offsets(data, SUBJECT))
    if not subjects:
        raise SystemExit("autogenerated kernel-key subject not found")

    candidates = set()
    for subject in subjects:
        search_start = max(0, subject - 8192)
        pos = search_start
        while True:
            hit = data.find(b"\x30\x82", pos, subject + 1)
            if hit < 0:
                break
            if hit + 4 <= len(data):
                length = int.from_bytes(data[hit + 2: hit + 4], "big") + 4
                end = hit + length
                if (
                    length >= 256
                    and end <= len(data)
                    and hit <= subject < end
                    and SUBJECT in data[hit:end]
                ):
                    candidates.add((hit, length))
            pos = hit + 1

    if not candidates:
        raise SystemExit("DER certificate containing autogenerated key subject not found")

    # X.509 contains nested DER sequences; select the outermost/largest object.
    cert_off, cert_len = max(candidates, key=lambda item: (item[1], -item[0]))
    cert = data[cert_off:cert_off + cert_len]
    if cert[:2] != b"\x30\x82" or SUBJECT not in cert:
        raise SystemExit("selected certificate failed structural validation")
    return cert_off, cert_len, cert

def main() -> int:
    ap = argparse.ArgumentParser(
        description="Describe reproducibility-normalization metadata for a pandora OS4 R62 Image."
    )
    ap.add_argument("image")
    ap.add_argument("--output-env")
    args = ap.parse_args()

    image = Path(args.image)
    data = image.read_bytes()
    bid = locate_top_level_build_id(data)
    cert_off, cert_len, cert = locate_autogenerated_cert(data)

    normalized = bytearray(data)
    normalized[bid:bid + 20] = b"\0" * 20
    normalized[cert_off:cert_off + cert_len] = b"\0" * cert_len

    values = {
        "IMAGE_SIZE": str(len(data)),
        "IMAGE_SHA256": hashlib.sha256(data).hexdigest(),
        "GNU_BUILD_ID": data[bid:bid + 20].hex(),
        "IMAGE_BUILD_ID_PAYLOAD_OFFSET": f"0x{bid:x}",
        "MODULE_SIGNING_CERT_SHA256": hashlib.sha256(cert).hexdigest(),
        "IMAGE_MODULE_CERT_OFFSET": f"0x{cert_off:x}",
        "IMAGE_MODULE_CERT_LENGTH": str(cert_len),
        "NORMALIZED_IMAGE_SHA256": hashlib.sha256(normalized).hexdigest(),
    }

    text = "".join(f"{key}={value}\n" for key, value in values.items())
    print(text, end="")
    if args.output_env:
        Path(args.output_env).write_text(text)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
